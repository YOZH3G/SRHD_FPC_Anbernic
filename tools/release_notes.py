#!/usr/bin/env python3
"""Port version and release notes from CHANGELOG.md and CHANGELOG_EN.md.

release_notes.py            write source/PortRelease.inc for the game
release_notes.py --check    fail when the include or the changelogs disagree
release_notes.py version    print the current version
release_notes.py notes V    print the release notes of version V (Markdown)
"""

import re
import sys

from targets import ROOT

CHANGELOGS = {"ru": ROOT / "CHANGELOG.md", "en": ROOT / "CHANGELOG_EN.md"}
INCLUDE = ROOT / "source/PortRelease.inc"
HEADING = re.compile(r"^## (\d+\.\d+\.\d+)(?: — (\d{4}-\d{2}-\d{2}))?$")


def sections(path):
    """Return [(version, [item, ...])] in file order; an item joins its lines."""
    result = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = HEADING.match(line)
        if match:
            result.append((match.group(1), []))
        elif result and line.startswith("- "):
            result[-1][1].append(line[2:].strip())
        elif result and line.startswith("  ") and result[-1][1]:
            result[-1][1][-1] += " " + line.strip()
        elif line.startswith("## "):
            raise SystemExit(f"{path.name}: bad version heading: {line}")
    return result


def load():
    data = {language: sections(path) for language, path in CHANGELOGS.items()}
    versions = [[version for version, _ in data[language]] for language in data]
    if not versions[0] or versions[0] != versions[1]:
        raise SystemExit("CHANGELOG.md and CHANGELOG_EN.md must list the same versions")
    return data


def pascal_string(text):
    # Markdown code spans become plain text, and the game's fonts have no
    # multiplication sign, dash or guillemets.
    text = text.replace("`", "").replace("**", "")
    for markdown, game in (("×", "x"), ("—", "-"), ("«", '"'), ("»", '"')):
        text = text.replace(markdown, game)
    return "'" + text.replace("'", "''") + "'"


def include_text(data):
    version = data["ru"][0][0]
    lines = [
        "// Generated by tools/release_notes.py from CHANGELOG.md and CHANGELOG_EN.md.",
        "// Do not edit.",
        f"PortVersion = '{version}';",
    ]
    for language, name in (("ru", "PortChangesRussian"), ("en", "PortChangesEnglish")):
        items = data[language][0][1]
        lines.append(f"{name} =")
        lines += [f"  '- ' + {pascal_string(item)} + #13#10 +" for item in items[:-1]]
        lines.append(f"  '- ' + {pascal_string(items[-1])};")
    return "\n".join(lines) + "\n"


def main():
    data = load()
    arguments = sys.argv[1:]
    if arguments == ["version"]:
        print(data["ru"][0][0])
    elif len(arguments) == 2 and arguments[0] == "notes":
        found = {language: dict(data[language]).get(arguments[1]) for language in data}
        if found["ru"] is None:
            raise SystemExit(f"No version {arguments[1]} in the changelogs")
        print("### Изменения\n")
        print("\n".join("- " + item for item in found["ru"]))
        print("\n### Changes\n")
        print("\n".join("- " + item for item in found["en"]))
    elif arguments == ["--check"]:
        if not INCLUDE.exists() or INCLUDE.read_text(encoding="utf-8") != include_text(data):
            raise SystemExit("source/PortRelease.inc is out of date: run tools/release_notes.py")
    elif not arguments:
        INCLUDE.write_text(include_text(data), encoding="utf-8")
        print(f"{INCLUDE.relative_to(ROOT)}: version {data['ru'][0][0]}")
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
