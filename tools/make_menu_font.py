#!/usr/bin/env python3
"""Generate the handheld main-menu caption font as AFT data for the game.

The game's own menu entries are artwork; this bitmap font letters added
entries close to it. It is rendered from Days One (SIL OFL 1.1, see
licenses/DaysOne-OFL.txt), stretched to the artwork's width, and written as a
Pascal include, so builds need neither the TTF nor Pillow. Run it again only
when the size, stretch, or characters change.
"""

import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

from targets import ROOT

SOURCE = ROOT / "tools/fonts/DaysOne-Regular.ttf"
OUTPUT = ROOT / "source/resources/HandheldMenuFont.inc"
# Capital height 15 px, letters 1.2 times wider and 2 px apart match the menu artwork.
SIZE = 21
STRETCH = 12  # tenths
TRACKING = 2
SUPERSAMPLE = 4
CHARACTERS = " ABCDEFGHIJKLMNOPQRSTUVWXYZЁАБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"


def rle(alpha: list[list[int]], keep, with_values: bool) -> bytes:
    """Encode one glyph plane the way OKGF's RLE builder does."""
    width = len(alpha[0])
    out = bytearray()
    for row in alpha:
        if not any(keep(value) for value in row) and width < 127:
            out.append(128)
            continue
        x = 0
        while x < width:
            literal = keep(row[x])
            n = 1
            while n < 127 and x + n < width and keep(row[x + n]) == literal:
                n += 1
            out.append(n | (128 if literal else 0))
            if literal and with_values:
                out += bytes(row[x : x + n])
            x += n
        out.append(0)
    return struct.pack("<4i", len(out), width, len(alpha), 0) + out


def render(font: ImageFont.FreeTypeFont, char: str):
    """Return the advance and, for a visible glyph, its box and coverage rows."""
    advance = round(font.getlength(char) * STRETCH / 10 / SUPERSAMPLE) + TRACKING
    left, top, right, bottom = font.getbbox(char, anchor="ls")
    # The canvas origin and size are whole target pixels, so the box filter
    # maps every target pixel to the same source area.
    step = SUPERSAMPLE * 10
    origin_x = -(left // step) * step + step
    origin_y = -(top // SUPERSAMPLE) * SUPERSAMPLE + SUPERSAMPLE
    width = (origin_x + right) // step * step + step
    height = (origin_y + bottom) // SUPERSAMPLE * SUPERSAMPLE + SUPERSAMPLE
    canvas = Image.new("L", (width, height), 0)
    ImageDraw.Draw(canvas).text((origin_x, origin_y), char, font=font, fill=255, anchor="ls")
    target = canvas.resize((width * STRETCH // 10 // SUPERSAMPLE, height // SUPERSAMPLE), Image.BOX)
    if target.getbbox() is None:
        return advance, None
    x0, y0, x1, y1 = target.getbbox()
    rows = [[target.getpixel((x, y)) for x in range(x0, x1)] for y in range(y0, y1)]
    return advance, (
        x0 - origin_x * STRETCH // 10 // SUPERSAMPLE,
        y0 - origin_y // SUPERSAMPLE,
        rows,
    )


def main() -> None:
    font = ImageFont.truetype(str(SOURCE), SIZE * SUPERSAMPLE)
    ascent, descent = (round(value / SUPERSAMPLE) for value in font.getmetrics())
    cap_height = len(render(font, "H")[1][2])
    records, planes = [], bytearray()
    data_start = 32 + 64 * len(CHARACTERS)
    for char in CHARACTERS:
        advance, glyph = render(font, char)
        if glyph is None:
            records.append(struct.pack("<I3i12i", ord(char), 0, 0, advance, *[0] * 12))
            continue
        left, top, rows = glyph
        width, height = len(rows[0]), len(rows)
        fields = []
        # Fully covered pixels go to the solid mask, edges to the alpha plane.
        for keep, with_values in ((lambda a: a >= 252, False), (lambda a: 0 < a < 252, True)):
            if not any(keep(a) for row in rows for a in row):
                fields += [0] * 6
                continue
            plane = rle(rows, keep, with_values)
            fields += [left, top, width, height, data_start + len(planes), len(plane)]
            planes += plane
        records.append(
            struct.pack("<I3i12i", ord(char), left, width, advance - left - width, *fields)
        )
    # The field after the centering height is the descent in the game's fonts.
    header = struct.pack(
        "<4s5i8s", b"aft\0", 1, len(CHARACTERS), cap_height, descent, ascent + descent, bytes(8)
    )
    data = header + b"".join(records) + planes
    lines = [
        ", ".join(f"${byte:02X}" for byte in data[i : i + 16]) for i in range(0, len(data), 16)
    ]
    OUTPUT.write_text(
        "// Generated by tools/make_menu_font.py from Days One (SIL OFL 1.1,\n"
        "// licenses/DaysOne-OFL.txt). Do not edit.\n"
        f"HandheldMenuFontData: array[0..{len(data) - 1}] of Byte = (\n  "
        + ",\n  ".join(lines)
        + "\n);\n",
        encoding="utf-8",
    )
    print(
        f"{OUTPUT.relative_to(ROOT)}: {len(CHARACTERS)} glyphs, {len(data)} bytes, capital height {cap_height}"
    )


if __name__ == "__main__":
    main()
